mod tests {
    use super::super::sha256;
    use super::*;

    #[test]
    fn prints_what_sha256sum_prints() {
        assert_eq!(
            hex(&sha256(b"abc")),
            "ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad"
        );
    }

    #[test]
    fn every_byte_becomes_two_characters_including_the_ones_below_sixteen() {
        assert_eq!(hex(&[0x00, 0x0f, 0xa0, 0xff]), "000fa0ff");
    }
}
